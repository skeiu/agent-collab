// 实验 12：从临时 web profile 用户层挑出 llm-* / agent-default-model 条目，生成 acp 覆盖层并验证当前模型。
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { assert, assertTempHome, createSandbox, findDsh, runDsh, stopChild } from '../_shared/harness.mjs';

const FAKE_PROVIDER = 'example-provider';
const FAKE_MODEL = 'example-model';

function topLevelBlocks(text) {
  const lines = text.split('\n');
  const blocks = [];
  let current;
  for (const line of lines) {
    if (line.startsWith('- ')) {
      if (current) blocks.push(current);
      current = [line];
    } else if (current) {
      current.push(line);
    }
  }
  if (current) blocks.push(current);
  return blocks.map((block) => block.join('\n').replace(/\n+$/, ''));
}

function selectOverlayEntries(text) {
  return topLevelBlocks(text).filter((block) => /^- id: (llm-|agent-default-model\b)/m.test(block));
}

function startAcp(env, dsh, overlay, cwd) {
  assertTempHome(env);
  const child = spawn(process.execPath, [dsh, '--profile', 'acp', '--patch', overlay], {
    env,
    cwd,
    stdio: ['pipe', 'pipe', 'pipe'],
  });
  let buffer = '';
  let stderr = '';
  const pending = new Map();
  child.stdout.setEncoding('utf8');
  child.stderr.setEncoding('utf8');
  child.stderr.on('data', (chunk) => { stderr += chunk; });
  child.stdout.on('data', (chunk) => {
    buffer += chunk;
    while (true) {
      const newline = buffer.indexOf('\n');
      if (newline < 0) break;
      const line = buffer.slice(0, newline).trim();
      buffer = buffer.slice(newline + 1);
      if (!line) continue;
      let message;
      try { message = JSON.parse(line); } catch { continue; }
      if (message.id !== undefined && pending.has(message.id)) {
        const entry = pending.get(message.id);
        pending.delete(message.id);
        clearTimeout(entry.timer);
        if (message.error) entry.reject(new Error('ACP error: ' + JSON.stringify(message.error)));
        else entry.resolve(message.result);
      }
    }
  });
  child.once('exit', (code, signal) => {
    for (const entry of pending.values()) {
      clearTimeout(entry.timer);
      entry.reject(new Error('ACP process exited: code=' + code + ' signal=' + signal + ' stderr=' + stderr.slice(-1000)));
    }
    pending.clear();
  });
  let nextId = 1;
  const request = (method, params) => new Promise((resolve, reject) => {
    const id = nextId++;
    const timer = setTimeout(() => {
      if (pending.delete(id)) reject(new Error('timeout waiting for ' + method + '; stderr=' + stderr.slice(-1000)));
    }, 60000);
    pending.set(id, { resolve, reject, timer });
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n');
  });
  return { child, request, stderr: () => stderr };
}

const box = createSandbox('12');
let acp;
try {
  const dsh = findDsh(box.env);
  const initWeb = runDsh(box.env, dsh, ['--profile', 'web', '--dump-config'], { timeoutMs: 60000 });
  assert(initWeb.status === 0, 'could not initialize web profile: ' + initWeb.stderr.slice(-1000));

  const webPatch = [
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    '      ' + FAKE_PROVIDER + ':',
    '        displayName: Example Provider',
    '        api: openai-completions',
    '        baseURL: http://127.0.0.1:9/v1',
    '        models:',
    '          - id: ' + FAKE_MODEL,
    '            name: Example Model',
    '            contextWindow: 8192',
    '- id: agent-default-model',
    '  config:',
    '    provider: ' + FAKE_PROVIDER,
    '    model: ' + FAKE_MODEL,
    '',
  ].join('\n');
  const webPatchPath = path.join(box.home, 'profiles', 'web', 'cordis.patch.yml');
  fs.writeFileSync(webPatchPath, webPatch);

  const webCheck = runDsh(box.env, dsh, ['--profile', 'web', '--dump-config'], { timeoutMs: 60000 });
  assert(webCheck.status === 0, 'fake web user layer did not load: ' + webCheck.stderr.slice(-1000));
  console.log('[12] fake web user layer loaded (llm-pi-ai + agent-default-model)');

  const entries = selectOverlayEntries(webPatch);
  console.log('[12] selected overlay entries: ' + entries.length);
  assert(entries.length === 2, 'expected 2 overlay entries, got ' + entries.length);
  const overlay = '# generated by experiments/1a/12-acp-overlay/run.mjs\n' + entries.join('\n') + '\n- id: acp\n  config:\n    provider: ' + FAKE_PROVIDER + '\n    model: ' + FAKE_MODEL + '\n';
  const overlayPath = path.join(box.root, 'acp-overlay.yml');
  fs.writeFileSync(overlayPath, overlay);
  console.log('[12] acp overlay:\n' + overlay);

  const work = path.join(box.root, 'workspace');
  fs.mkdirSync(work, { recursive: true });
  acp = startAcp(box.env, dsh, overlayPath, work);
  const init = await acp.request('initialize', { protocolVersion: 1 });
  console.log('[12] initialize ok: ' + init.agentInfo.name + ' protocol=' + init.protocolVersion);
  const created = await acp.request('session/new', { cwd: work, mcpServers: [] });
  console.log('[12] session/new sessionId=' + created.sessionId);
  const modelOption = created.configOptions.find((option) => option.id === 'model');
  assert(modelOption, 'session/new returned no model config option');
  console.log('[12] current model option: ' + modelOption.currentValue);
  assert(modelOption.currentValue === JSON.stringify([FAKE_PROVIDER, FAKE_MODEL]), 'current model is not the overlay selection');
  const group = modelOption.options.find((item) => item.group === FAKE_PROVIDER);
  assert(group, 'provider group missing from model options');
  assert(group.options.some((item) => item.value === JSON.stringify([FAKE_PROVIDER, FAKE_MODEL])), 'fake model missing from model options');

  console.log('RESULT: 成立 — 从 web 用户层挑出 llm-* 与 agent-default-model 条目并加上 acp 的 provider/model 可生成覆盖层；dsh --profile acp --patch 正常加载，initialize 成功，session/new 返回的当前模型就是覆盖层指定的 ' + FAKE_PROVIDER + '/' + FAKE_MODEL + '。');
} finally {
  if (acp) await stopChild(acp.child);
  box.cleanup();
}
