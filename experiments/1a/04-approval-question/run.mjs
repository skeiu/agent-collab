// 实验 04：审批和 ask_user_question 能否通过 session/event 观察、能否由插件应答；使用真实模型。
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { assert, createSandbox, enablePnpm, findDsh, installPlugin, makePlugin, readJson, runDsh, startWeb, stopChild, waitFor } from '../_shared/harness.mjs';

function expandHome(value) {
  if (value === '~') return os.homedir();
  if (value.startsWith('~/')) return path.join(os.homedir(), value.slice(2));
  return value;
}

function topLevelBlocks(text) {
  const lines = text.split('\n');
  const blocks = [];
  let current;
  for (const line of lines) {
    if (line.startsWith('- ')) {
      if (current) blocks.push(current);
      current = [line];
    } else if (current) {
      current.push(line);
    }
  }
  if (current) blocks.push(current);
  return blocks.map((block) => block.join('\n').replace(/\n+$/, ''));
}

function selectModelEntries(text) {
  const selected = [];
  for (const block of topLevelBlocks(text)) {
    const match = /^- id:\s*(\S+)/.exec(block);
    const id = match?.[1];
    if (id !== undefined && (id.startsWith('llm-') || id === 'agent-default-model')) selected.push(block);
  }
  return selected;
}

function overrideModel(block, model) {
  if (!/^- id:\s*agent-default-model\b/.test(block)) return block;
  let replaced = false;
  const next = block.split('\n').map((line) => {
    if (replaced) return line;
    const match = /^(\s+model:\s*).*$/.exec(line);
    if (!match) return line;
    replaced = true;
    return match[1] + JSON.stringify(model);
  }).join('\n');
  return replaced ? next : block;
}

const realHome = process.env.AC_REAL_DSH_HOME;
if (!realHome) {
  console.error('AC_REAL_DSH_HOME is not set; refusing to guess the real DSH_HOME');
  process.exit(2);
}
const realHomePath = path.resolve(expandHome(realHome));
const realProfile = process.env.AC_REAL_DSH_PROFILE || 'web';
const realPatchPath = path.join(realHomePath, 'profiles', realProfile, 'cordis.patch.yml');
if (!fs.existsSync(realPatchPath)) {
  console.error('real profile patch was not found (check AC_REAL_DSH_HOME and AC_REAL_DSH_PROFILE)');
  process.exit(2);
}

const box = createSandbox('04');
const envLink = path.join(box.home, '.env');
let web;
try {
  const dsh = findDsh(box.env);
  enablePnpm(box.env, box.root);

  const init = runDsh(box.env, dsh, ['--profile', 'web', '--dump-config'], { timeoutMs: 60000 });
  assert(init.status === 0, 'could not initialize the temporary web profile');

  const entries = selectModelEntries(fs.readFileSync(realPatchPath, 'utf8'));
  assert(entries.some((block) => /^- id:\s*llm-/.test(block)), 'no llm-* entry found in the real profile patch');
  assert(entries.some((block) => /^- id:\s*agent-default-model\b/.test(block)), 'no agent-default-model entry found in the real profile patch');
  const testModel = process.env.AC_TEST_MODEL || undefined;
  const modelEntries = testModel === undefined
    ? entries
    : entries.map((block) => overrideModel(block, testModel));
  const tempWebPatch = path.join(box.home, 'profiles', 'web', 'cordis.patch.yml');
  fs.writeFileSync(tempWebPatch, '# generated by experiments/1a/04-approval-question/run.mjs\n' + modelEntries.join('\n\n') + '\n');
  const check = runDsh(box.env, dsh, ['--profile', 'web', '--dump-config'], { timeoutMs: 60000 });
  assert(check.status === 0, 'temporary web profile did not load after writing the model entries');
  console.log('[04] selected ' + entries.length + ' model entries from the real profile');

  const realEnv = path.join(realHomePath, '.env');
  fs.symlinkSync(realEnv, envLink, 'file');
  assert(fs.lstatSync(envLink).isSymbolicLink(), '.env link was not created as a symbolic link');
  assert(fs.readlinkSync(envLink) === realEnv, '.env link target does not match');

  const tgz = makePlugin(box.root, box.env, {
    name: 'dsh-exp-04-approval-question',
    version: '1.0.0',
    main: fs.readFileSync(new URL('./plugin/index.js', import.meta.url), 'utf8'),
    patch: fs.readFileSync(new URL('./plugin/cordis.patch.yml', import.meta.url), 'utf8'),
  });
  const installed = installPlugin(box.env, dsh, 'web', tgz);
  assert(installed.status === 0, 'dsh plugin add failed: ' + installed.stderr.slice(-1000));

  web = await startWeb(box.env, dsh);
  console.log('[04] dsh web ready on port ' + web.port);

  const outFile = path.join(box.home, 'exp-04.json');
  const errorFile = path.join(box.home, 'exp-04-error.json');
  let ready;
  try {
    ready = await waitFor(() => {
      if (fs.existsSync(outFile)) return 'result';
      if (fs.existsSync(errorFile)) return 'error';
      return null;
    }, 540000, 'exp-04.json');
  } catch (error) {
    let log = '';
    try { log = fs.readFileSync(path.join(box.home, 'exp-04.log'), 'utf8'); } catch {}
    console.log('[04] plugin log tail: ' + log.slice(-2000));
    throw error;
  }
  if (ready === 'error') {
    console.log('[04] plugin error: ' + fs.readFileSync(errorFile, 'utf8').slice(0, 3000));
    throw new Error('plugin reported an error');
  }

  const result = readJson(outFile);
  const byKind = Object.fromEntries(result.sessions.map((session) => [session.kind, session]));
  const approve = byKind.approve;
  const reject = byKind.reject;
  const question = byKind.question;

  const asked = (session) => session.approvalEvents.filter((event) => event.type === 'approval/asked');
  const decided = (session) => session.approvalEvents.filter((event) => event.type === 'approval/decided');
  const outcome = (session) => decided(session)[0]?.data?.outcome ?? null;
  const statuses = [...asked(approve), ...decided(approve), ...asked(reject), ...decided(reject)].map((event) => event.agentStatus);

  const questionCalls = question.toolCalls.filter((call) => call.name === 'ask_user_question');
  const questionRequest = question.questionRequests[0] ?? null;
  const questionResult = question.toolResults.find((item) => item.callId === questionCalls[0]?.callId) ?? null;
  const answerInToolResult = questionResult !== null && questionResult.content.includes(result.answerToken);
  const answerInFinal = question.finalText.includes(result.answerToken);

  const askedExcerpt = asked(approve)[0];
  console.log('[04] approval/asked excerpt: ' + JSON.stringify({
    type: askedExcerpt?.type,
    id: askedExcerpt?.data?.id?.slice(0, 8),
    toolName: askedExcerpt?.data?.toolName,
    callId: askedExcerpt?.data?.callId?.slice(0, 8),
    reason: askedExcerpt?.data?.reason,
    agentStatus: askedExcerpt?.agentStatus,
  }));
  console.log('[04] approval/decided excerpt: ' + JSON.stringify({
    type: decided(approve)[0]?.type,
    id: decided(approve)[0]?.data?.id?.slice(0, 8),
    outcome: decided(approve)[0]?.data?.outcome,
    agentStatus: decided(approve)[0]?.agentStatus,
  }));
  console.log('[04] approval allow: asked=' + asked(approve).length + ' decided=' + decided(approve).length +
    ' outcome=' + outcome(approve) + ' status-at-asked=' + (asked(approve)[0]?.agentStatus ?? 'n/a') +
    ' status-at-decided=' + (decided(approve)[0]?.agentStatus ?? 'n/a') +
    ' status-at-when-idle=' + (approve.statusSamples.find((item) => item.at === 'when-idle')?.status ?? 'n/a') +
    ' file=' + (approve.file?.exists ? 'written' : 'absent'));
  console.log('[04] approval reject: asked=' + asked(reject).length + ' decided=' + decided(reject).length +
    ' outcome=' + outcome(reject) + ' status-at-asked=' + (asked(reject)[0]?.agentStatus ?? 'n/a') +
    ' file=' + (reject.file?.exists ? 'written' : 'absent'));
  console.log('[04] question tool/call excerpt: ' + JSON.stringify({
    name: questionCalls[0]?.name,
    callId: questionCalls[0]?.callId?.slice(0, 8),
    questions: questionCalls[0]?.questions,
  }));
  console.log('[04] question service request: ' + JSON.stringify({
    wait: questionRequest?.wait,
    requestKeys: questionRequest?.requestKeys,
    questions: questionRequest?.questions,
    projectionTimed: questionRequest?.projectionTimed,
    projectionActiveCount: questionRequest?.projectionActive?.length ?? 0,
  }));
  console.log('[04] question: tool/call=' + (questionCalls.length > 0 ? 'seen' : 'missing') +
    ' projection-timed=' + String(questionRequest?.projectionTimed) +
    ' projection-active=' + (questionRequest?.projectionActive?.length ?? 0) +
    ' answered-by-plugin=' + (questionRequest !== null ? 'yes' : 'no') +
    ' answer-in-tool-result=' + (answerInToolResult ? 'yes' : 'no') +
    ' answer-in-final=' + (answerInFinal ? 'yes' : 'no'));
  if (question.finalText) console.log('[04] question final text: ' + JSON.stringify(question.finalText.slice(0, 200)));
  const usage = result.sessions.flatMap((session) => session.usages ?? []);
  const sum = (key) => usage.reduce((total, item) => total + (item[key] ?? 0), 0);
  console.log('[04] usage: model-responses=' + usage.length + ' input=' + sum('inputTokens') + ' output=' + sum('outputTokens') + ' total=' + sum('totalTokens'));

  const q1 = asked(approve).length > 0 && decided(approve).length > 0 && asked(reject).length > 0 && decided(reject).length > 0;
  const q2 = q1 && statuses.length > 0 && statuses.every((status) => status === 'running');
  const q3 = outcome(approve) === 'allowed-once' && outcome(reject) === 'rejected' &&
    approve.file?.exists === true && reject.file?.exists === false;
  const q4 = questionCalls.length > 0 && questionRequest !== null &&
    (questionRequest.questions ?? []).length > 0 && answerInToolResult && answerInFinal;

  if (q1 && q2 && q3 && q4) {
    console.log('RESULT: 成立 — 审批的 approval/asked 与 approval/decided 能通过 session/event 收到（字段 id、toolName、callId、reason、outcome），插件作为 approval/request 的应答者可以分别返回 allowed-once 和 rejected；审批等待期间 agent.status 始终是 running，不能单独判断“等待审批”，但事件对可以；ask_user_question 的完整提问出现在 tool/call 事件和 user-questions/request 的请求里，插件在 user-questions/request 返回答案后模型能在工具结果和回复中复述；标准预设的 legacy 模式下 userQuestions 投影 active 为空（投影只记录 timed 模式），不能靠投影看待答问题。');
  } else {
    const failed = [q1 ? null : '审批事件', q2 ? null : '状态/事件判断', q3 ? null : '批准或拒绝', q4 ? null : '提问与回答'].filter(Boolean);
    console.log('RESULT: 部分成立 — 未通过的部分：' + failed.join('、') + '；详见上面的输出和 exp-04.json。');
  }
} finally {
  if (web) await stopChild(web.child);
  try {
    if (fs.lstatSync(envLink).isSymbolicLink()) fs.unlinkSync(envLink);
  } catch {}
  box.cleanup();
}
